create table outbox_events (
    id             bigint generated by default as identity primary key,
    event_id       uuid         not null,
    aggregate_type varchar(100) not null,
    aggregate_id   varchar(100) not null,
    event_type     varchar(100) not null,
    topic          varchar(200) not null,
    message_key    varchar(200) not null,
    payload        jsonb        not null,
    created_at     timestamptz  not null,
    published_at   timestamptz,
    constraint uk_outbox_events_event_id unique (event_id)
);

-- The relay only ever scans unpublished rows; a partial index keeps that cheap as history grows.
create index ix_outbox_events_unpublished on outbox_events (id) where published_at is null;
