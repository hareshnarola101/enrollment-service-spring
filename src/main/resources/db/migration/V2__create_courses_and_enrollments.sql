create table courses (
    id          bigint generated by default as identity primary key,
    code        varchar(20)  not null,
    title       varchar(200) not null,
    description varchar(2000),
    capacity    integer      not null,
    seats_taken integer      not null default 0,
    created_at  timestamptz  not null,
    updated_at  timestamptz  not null,
    constraint uk_courses_code unique (code),
    constraint ck_courses_capacity check (capacity > 0),
    -- Last line of defence against overbooking, whatever the application does.
    constraint ck_courses_seats check (seats_taken >= 0 and seats_taken <= capacity)
);

create table enrollments (
    id         bigint generated by default as identity primary key,
    course_id  bigint      not null references courses (id),
    student_id bigint      not null references users (id),
    status     varchar(20) not null,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint ck_enrollments_status check (status in ('PENDING', 'CONFIRMED', 'WAITLISTED', 'CANCELLED'))
);

-- A student can have at most one live enrollment per course; cancelled ones are history.
create unique index ux_enrollments_active_student_course
    on enrollments (course_id, student_id)
    where status in ('PENDING', 'CONFIRMED', 'WAITLISTED');

-- Serves the waitlist lookup (course, status, arrival order) and per-course listings.
create index ix_enrollments_course_status_created on enrollments (course_id, status, created_at, id);
create index ix_enrollments_student on enrollments (student_id, created_at);
